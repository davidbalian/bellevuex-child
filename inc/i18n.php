<?php
/**
 * Chic Centre Suites — custom i18n layer.
 *
 * Path-prefix model: English (default) has no prefix; Greek lives under /el/.
 * Uses WordPress query_vars + add_rewrite_rule; no Polylang/WPML dependency.
 */
defined( 'ABSPATH' ) || exit;

/* ── Constants ───────────────────────────────────────────────────────────── */

define( 'CHIC_DEFAULT_LANG',    'en' );
define( 'CHIC_SUPPORTED_LANGS', [ 'en', 'el' ] );
define( 'CHIC_I18N_VERSION',    '2' );

/* ── Language detection ──────────────────────────────────────────────────── */

function chic_get_current_lang(): string {
	static $lang = null;
	if ( null !== $lang ) {
		return $lang;
	}
	$qv = (string) get_query_var( 'lang', '' );
	if ( $qv && in_array( $qv, CHIC_SUPPORTED_LANGS, true ) ) {
		$lang = $qv;
		return $lang;
	}
	$path     = trim( (string) parse_url( $_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH ), '/' );
	$segments = explode( '/', $path );
	if ( ! empty( $segments[0] ) && in_array( $segments[0], [ 'el' ], true ) ) {
		$lang = $segments[0];
		return $lang;
	}
	$lang = CHIC_DEFAULT_LANG;
	return $lang;
}

/* ── Rewrite rules ───────────────────────────────────────────────────────── */

add_action( 'init', function () {
	add_rewrite_rule( '^el/?$',          'index.php?lang=el',                          'top' );
	add_rewrite_rule( '^el/(.+?)/?$',    'index.php?lang=el&pagename=$matches[1]',     'top' );
	// Registered last so WP checks it first among `top` rules: Greek MotoPress singles.
	add_rewrite_rule(
		'^el/accommodation/([^/]+)/?$',
		'index.php?lang=el&post_type=mphb_room_type&name=$matches[1]',
		'top'
	);
}, 1 );

add_filter( 'query_vars', function ( array $vars ): array {
	$vars[] = 'lang';
	return $vars;
} );

// Remap Greek request vars before parse_query runs, so WP sets conditionals correctly.
add_filter( 'request', function ( array $query_vars ): array {
	if ( ( $query_vars['lang'] ?? '' ) !== 'el' ) {
		return $query_vars;
	}

	// Remap pagename=accommodation/slug to the accommodation CPT.
	$pagename = $query_vars['pagename'] ?? '';
	if ( is_string( $pagename ) && '' !== $pagename
		&& preg_match( '#^accommodation/([^/]+)$#', $pagename, $m ) ) {
		unset( $query_vars['pagename'] );
		$query_vars['post_type'] = 'mphb_room_type';
		$query_vars['name']      = $m[1];
		return $query_vars;
	}

	// Bare /el/ → inject the static front page's slug so parse_query resolves it as
	// a normal page request (sets is_page + is_front_page correctly, before templates
	// are chosen). Setting page_id in pre_get_posts was too late — conditionals were
	// already baked in, causing the parent theme's home.php to load instead.
	if ( empty( $query_vars['pagename'] )
		&& empty( $query_vars['name'] )
		&& empty( $query_vars['page_id'] )
		&& empty( $query_vars['p'] )
		&& 'page' === get_option( 'show_on_front' ) ) {
		$front_id = (int) get_option( 'page_on_front' );
		if ( $front_id > 0 ) {
			$front = get_post( $front_id );
			if ( $front instanceof WP_Post && 'publish' === $front->post_status ) {
				$query_vars['pagename'] = $front->post_name;
			}
		}
	}

	return $query_vars;
}, 5 );

// Flush rewrite rules on theme activation.
add_action( 'after_switch_theme', function () {
	flush_rewrite_rules();
} );

// Flush when our version bumps.
add_action( 'init', function () {
	if ( get_option( 'chic_i18n_version' ) !== CHIC_I18N_VERSION ) {
		flush_rewrite_rules();
		update_option( 'chic_i18n_version', CHIC_I18N_VERSION );
	}
}, 99 );

/* ── Physical /el/ directory shim ────────────────────────────────────────── */

/**
 * The Sitemap & LLMs.txt tool writes el/llms.txt, which forces a real `el`
 * directory into ABSPATH. That directory shadows our `^el/?$` rewrite rule.
 * WordPress's root .htaccess skips existing directories (RewriteCond !-d), so
 * the server tries to serve the folder itself and returns 403 Forbidden when
 * directory listing is off, which is the case on every production host.
 *
 * The tool drops an el/.htaccess to route around it, but that only helps on
 * Apache with AllowOverride enabled. An index.php inside the directory works
 * on Apache, Nginx and LiteSpeed alike. The server resolves it as the
 * DirectoryIndex, it boots WordPress, and WP matches /el/ against its own
 * rewrite rules exactly as if the directory never existed.
 *
 * Bump CHIC_EL_SHIM_VERSION to force a rewrite of the shim on next admin load.
 */
define( 'CHIC_EL_SHIM_VERSION', '1' );

function chic_el_dir_shim_contents(): string {
	return <<<'PHP'
<?php
/**
 * Auto-generated by the Chic Centre Suites child theme. Do not edit.
 * @see inc/i18n.php, function chic_el_ensure_dir_shim()
 *
 * The physical el/ directory (created to host el/llms.txt) shadows the theme's
 * ^el/?$ rewrite rule, so the server never hands /el/ to WordPress and returns
 * 403. This file is the DirectoryIndex for that folder. It boots WordPress,
 * which then matches the untouched REQUEST_URI (/el/) against its own rules.
 */
require dirname( __DIR__ ) . '/index.php';
PHP;
}

/**
 * Write el/index.php if the physical directory exists and the shim is missing
 * or out of date. Never creates the directory. If there is no el/ folder then
 * the rewrite rules already work and there is nothing to fix.
 */
function chic_el_ensure_dir_shim(): bool {
	$dir = ABSPATH . 'el';
	if ( ! is_dir( $dir ) ) {
		return false;
	}

	$shim     = $dir . '/index.php';
	$contents = chic_el_dir_shim_contents();

	if ( is_file( $shim ) ) {
		$existing = (string) file_get_contents( $shim );
		if ( $existing === $contents ) {
			return true;
		}
		// Only overwrite a file we generated ourselves, never a hand-written one.
		if ( false === strpos( $existing, 'chic_el_ensure_dir_shim' ) ) {
			return false;
		}
	}

	return false !== file_put_contents( $shim, $contents, LOCK_EX );
}

// Self-heal on admin load, once per shim version.
add_action( 'admin_init', function () {
	if ( get_option( 'chic_el_shim_version' ) === CHIC_EL_SHIM_VERSION ) {
		return;
	}
	chic_el_ensure_dir_shim();
	update_option( 'chic_el_shim_version', CHIC_EL_SHIM_VERSION );
} );

/* ── Canonical redirect guard ────────────────────────────────────────────── */

add_filter( 'redirect_canonical', function ( $redirect_url, $requested_url ) {
	$path = trim( (string) parse_url( $requested_url ?? $_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH ), '/' );
	if ( strncmp( $path, 'el/', 3 ) === 0 || $path === 'el' ) {
		return false;
	}
	return $redirect_url;
}, 10, 2 );

/* ── HTML lang attribute ─────────────────────────────────────────────────── */

add_filter( 'language_attributes', function ( string $output ): string {
	$map = [
		'en' => 'en-US',
		'el' => 'el-GR',
	];
	$lang = chic_get_current_lang();
	if ( isset( $map[ $lang ] ) ) {
		return 'lang="' . esc_attr( $map[ $lang ] ) . '"';
	}
	return $output;
} );

/* ── Translation helpers ─────────────────────────────────────────────────── */

function chic_get_translations( string $lang ): array {
	static $cache = [];
	if ( isset( $cache[ $lang ] ) ) {
		return $cache[ $lang ];
	}
	if ( $lang === CHIC_DEFAULT_LANG ) {
		$cache[ $lang ] = [];
		return $cache[ $lang ];
	}
	$file = get_stylesheet_directory() . '/translations/' . $lang . '.php';
	$cache[ $lang ] = file_exists( $file ) ? include $file : [];
	return $cache[ $lang ];
}

function t( string $key ): string {
	$lang = chic_get_current_lang();
	if ( $lang === CHIC_DEFAULT_LANG ) {
		return $key;
	}
	$map = chic_get_translations( $lang );
	return $map[ $key ] ?? $key;
}

/**
 * Greek translation from translations/el.php regardless of current locale.
 * Used by ACF seeding/backfill in wp-admin where chic_get_current_lang() is always en.
 */
function t_el( string $en ): string {
	$map = chic_get_translations( 'el' );
	return $map[ $en ] ?? $en;
}

