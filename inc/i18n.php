}

/**
 * Strip monotonic Greek tonos / dialytika for copy shown in all-caps UI (see theme CSS).
 * No-op when not on Greek locale or when intl Normalizer is unavailable (limited fallback).
 */
function chic_el_strip_monotonic_tonos( string $text ): string {
	if ( $text === '' || chic_get_current_lang() !== 'el' ) {
		return $text;
	}
	static $precomposed = [
		'Ά' => 'Α', 'Έ' => 'Ε', 'Ή' => 'Η', 'Ί' => 'Ι', 'Ό' => 'Ο', 'Ύ' => 'Υ', 'Ώ' => 'Ω',
		'Ϊ' => 'Ι', 'Ϋ' => 'Υ',
	];
	$text = strtr( $text, $precomposed );
	if ( class_exists( 'Normalizer', false ) ) {
		$norm = Normalizer::normalize( $text, Normalizer::FORM_D );
		if ( is_string( $norm ) && '' !== $norm ) {
			$norm = preg_replace( '/[\x{0301}\x{0308}\x{0342}\x{0344}\x{0345}]/u', '', $norm );
			$nfc  = Normalizer::normalize( $norm, Normalizer::FORM_C );
			if ( is_string( $nfc ) ) {
				$text = $nfc;
			} else {
				$text = $norm;
			}
		}
	} else {
		static $lower = [
			'ά' => 'α', 'έ' => 'ε', 'ή' => 'η', 'ί' => 'ι', 'ό' => 'ο', 'ύ' => 'υ', 'ώ' => 'ω',
			'ϊ' => 'ι', 'ΐ' => 'ι', 'ϋ' => 'υ', 'ΰ' => 'υ',
		];
		$text = strtr( $text, $lower );
	}
	return $text;
}

/** Translation for all-caps / uppercase-styled Greek (buttons, certain headings). */
function t_uc( string $key ): string {
	return chic_el_strip_monotonic_tonos( t( $key ) );
}

function te_uc( string $key ): void {
	echo esc_html( t_uc( $key ) );
}

function ta_uc( string $key ): string {
	return esc_attr( t_uc( $key ) );
}

function t_uc_html( string $key ): string {
	return chic_el_strip_monotonic_tonos( t_html( $key ) );
}

/* ── Suite title translation helper ─────────────────────────────────────── */

function chic_translate_suite_title( string $english_title ): string {
	if ( chic_get_current_lang() === CHIC_DEFAULT_LANG ) {
		return $english_title;
	}
	// "Forest Suite" → "Σουίτα Forest"
	if ( preg_match( '/^(.+?)\s+Suite$/i', $english_title, $m ) ) {
		return t( 'Suite' ) . ' ' . $m[1];
	}
	// "Suite 3" → "Σουίτα 3"
	if ( preg_match( '/^Suite\s+(.+)$/i', $english_title, $m ) ) {
		return t( 'Suite' ) . ' ' . $m[1];
	}
	return $english_title;
}

/** Suite title for `.suite-card__title` / `.suite-hero__title` (all-caps CSS); keeps tonos in `chic_translate_suite_title()` for other uses. */
function chic_translate_suite_title_uc( string $english_title ): string {
	return chic_el_strip_monotonic_tonos( chic_translate_suite_title( $english_title ) );
}

/* ── URL builders ────────────────────────────────────────────────────────── */

function chic_localized_url( string $path = '/', ?string $lang = null ): string {
	$lang = $lang ?? chic_get_current_lang();
	$path = '/' . ltrim( $path, '/' );
	if ( $lang === CHIC_DEFAULT_LANG ) {
		return home_url( $path );
	}
	return home_url( '/' . $lang . $path );
}

/**
 * Prefix absolute permalinks with /el/ on Greek front-end requests.
 */
function chic_localize_front_permalink( string $url ): string {
	if ( '' === $url || CHIC_DEFAULT_LANG === chic_get_current_lang() ) {
		return $url;
	}
	if ( is_admin() ) {
		return $url;
	}
	$rel = wp_make_link_relative( $url );
	if ( $rel === $url || '' === $rel ) {
		return $url;
	}
	return chic_localized_url( $rel );
}

add_filter(
	'post_type_link',
	function ( string $post_link, $post, $leavename = false, $sample = false ): string {
		if ( $sample || ! $post instanceof WP_Post || 'mphb_room_type' !== $post->post_type ) {
			return $post_link;
		}
		return chic_localize_front_permalink( $post_link );
	},
	10,
	4
);

add_filter(
	'page_link',
	function ( string $link, int $post_id, bool $sample = false ): string {
		if ( $sample ) {
			return $link;
		}
		return chic_localize_front_permalink( $link );
	},
	10,
	3
);

function chic_lang_switch_url( string $target_lang ): string {
	$raw_path  = (string) parse_url( $_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH );
	$clean     = trim( $raw_path, '/' );
	// Strip existing language prefix (el) from the path.
	foreach ( CHIC_SUPPORTED_LANGS as $code ) {
		if ( $code === CHIC_DEFAULT_LANG ) continue;
		if ( strncmp( $clean, $code . '/', strlen( $code ) + 1 ) === 0 ) {
			$clean = substr( $clean, strlen( $code ) + 1 );
			break;
		}
		if ( $clean === $code ) {
			$clean = '';
			break;
		}
	}
	if ( $target_lang === CHIC_DEFAULT_LANG ) {
		return home_url( '/' . ( $clean ? $clean . '/' : '' ) );
	}
	return home_url( '/' . $target_lang . '/' . ( $clean ? $clean . '/' : '' ) );
}

/* ── Browser-language redirect (first visit) ─────────────────────────────── */

add_action( 'template_redirect', function () {
	$path = trim( (string) parse_url( $_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH ), '/' );
	if ( $path !== '' ) return;
	if ( ! empty( $_COOKIE['mci_lang'] ) ) return;

	// Skip known crawlers.
	$ua = strtolower( $_SERVER['HTTP_USER_AGENT'] ?? '' );
	if ( preg_match( '/bot|crawl|spider|slurp|bing|yandex|baidu|duckduckbot|facebookexternalhit|twitterbot|googlebot/', $ua ) ) {
		return;
	}

	$accept  = $_SERVER['HTTP_ACCEPT_LANGUAGE'] ?? '';
	$matched = null;
	// Parse quality values.
	$parts = explode( ',', $accept );
	$langs_q = [];
	foreach ( $parts as $part ) {
		$part = trim( $part );
		if ( preg_match( '/^([a-zA-Z]{1,8}(?:-[a-zA-Z0-9]{1,8})?)\s*(?:;\s*q=([\d.]+))?$/', $part, $m ) ) {
			$code = strtolower( substr( $m[1], 0, 2 ) );
			$q    = isset( $m[2] ) ? (float) $m[2] : 1.0;
			if ( ! isset( $langs_q[ $code ] ) || $langs_q[ $code ] < $q ) {
				$langs_q[ $code ] = $q;
			}
		}
	}
	arsort( $langs_q );
	foreach ( array_keys( $langs_q ) as $code ) {
		if ( $code === 'el' ) { $matched = 'el'; break; }
	}

	if ( $matched ) {
		setcookie( 'mci_lang', $matched, [
			'expires'  => time() + 60 * 60 * 24 * 365,
			'path'     => '/',
			'samesite' => 'Lax',
		] );
		wp_safe_redirect( home_url( '/' . $matched . '/' ), 302 );
		exit;
	}

	setcookie( 'mci_lang', 'en', [
		'expires'  => time() + 60 * 60 * 24 * 365,
		'path'     => '/',
		'samesite' => 'Lax',
	] );
}, 5 );

// Sync cookie when user manually navigates to a prefixed URL.
